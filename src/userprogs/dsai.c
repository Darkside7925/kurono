// ---------------------------------------------------------------- growable buf

typedef struct {
    char  *p;
    size_t len;
    size_t cap;
} buf_t;

static void buf_init(buf_t *b) { b->p = NULL; b->len = 0; b->cap = 0; }

static void buf_free(buf_t *b) { free(b->p); buf_init(b); }

static int buf_reserve(buf_t *b, size_t extra)
{
    if (b->len + extra + 1 <= b->cap) return 0;
    size_t want = b->cap ? b->cap : 1024;
    while (want < b->len + extra + 1) want *= 2;
    char *np = realloc(b->p, want);
    if (!np) return -1;
    b->p = np;
    b->cap = want;
    return 0;
}

static int buf_add(buf_t *b, const char *s, size_t n)
{
    if (buf_reserve(b, n) < 0) return -1;
    memcpy(b->p + b->len, s, n);
    b->len += n;
    b->p[b->len] = 0;
    return 0;
}

static int buf_puts(buf_t *b, const char *s) { return buf_add(b, s, strlen(s)); }

// append s as a json string body, escaped, without the surrounding quotes.
// the model sees raw command output, which is full of quotes, backslashes and
// control bytes, so this has to be correct or the request is rejected. (satoru)
static int buf_json_escape(buf_t *b, const char *s, size_t n)
{
    char tmp[8];
    for (size_t i = 0; i < n; i++) {
        unsigned char c = (unsigned char)s[i];
        switch (c) {
        case '"':  if (buf_puts(b, "\\\"") < 0) return -1; break;
        case '\\': if (buf_puts(b, "\\\\") < 0) return -1; break;
        case '\n': if (buf_puts(b, "\\n")  < 0) return -1; break;
        case '\r': if (buf_puts(b, "\\r")  < 0) return -1; break;
        case '\t': if (buf_puts(b, "\\t")  < 0) return -1; break;
        case '\b': if (buf_puts(b, "\\b")  < 0) return -1; break;
        case '\f': if (buf_puts(b, "\\f")  < 0) return -1; break;
        default:
            if (c < 0x20) {
                snprintf(tmp, sizeof tmp, "\\u%04x", c);
                if (buf_puts(b, tmp) < 0) return -1;
            } else {
                if (buf_add(b, (const char *)&c, 1) < 0) return -1;
            }
        }
    }
    return 0;
}

// ---------------------------------------------------------------- tiny json

// these are deliberately not a real parser. we only ever consume responses this
// program itself asked for, with a shape the api documents, so a scanner that
// understands strings-with-escapes and nesting depth is enough and cannot run
// away on malformed input. (satoru)

static const char *json_skip_ws(const char *p)
{
    while (*p && (*p == ' ' || *p == '\t' || *p == '\n' || *p == '\r')) p++;
    return p;
}

// step over one json value starting at p, return the byte after it
static const char *json_skip_value(const char *p)
{
    p = json_skip_ws(p);
    if (!*p) return p;
    if (*p == '"') {
        p++;
        while (*p) {
            if (*p == '\\' && p[1]) { p += 2; continue; }
            if (*p == '"') return p + 1;
            p++;
        }
        return p;
    }
    if (*p == '{' || *p == '[') {
        int depth = 0;
        while (*p) {
            if (*p == '"') { p = json_skip_value(p); continue; }
            if (*p == '{' || *p == '[') depth++;
            else if (*p == '}' || *p == ']') { depth--; if (!depth) return p + 1; }
            p++;
        }
        return p;
    }
    while (*p && *p != ',' && *p != '}' && *p != ']') p++;
    return p;
}

// find "key" at the current object level or deeper, return the value start.
// scan-based, so it finds the first match in document order - fine for the
// fields we want, all of which appear once in the shapes we request. (satoru)
static const char *json_find(const char *p, const char *key)
{
    size_t klen = strlen(key);
    while (*p) {
        if (*p == '"') {
            const char *ks = p + 1;
            const char *ke = json_skip_value(p);
            if (ke > ks + 1 && (size_t)(ke - 1 - ks) == klen &&
                !memcmp(ks, key, klen)) {
                const char *v = json_skip_ws(ke);
                if (*v == ':') return json_skip_ws(v + 1);
            }
            p = ke;
            continue;
        }
        p++;
    }
    return NULL;
}

// decode a json string value into a fresh malloc'd c string
static char *json_str_dup(const char *p)
{
    if (!p || *p != '"') return NULL;
    p++;
    buf_t out;
    buf_init(&out);
    while (*p && *p != '"') {
        if (*p == '\\' && p[1]) {
            p++;
            char c = 0;
            switch (*p) {
            case 'n': c = '\n'; break;
            case 't': c = '\t'; break;
            case 'r': c = '\r'; break;
            case 'b': c = '\b'; break;
            case 'f': c = '\f'; break;
            case '/': c = '/';  break;
            case '"': c = '"';  break;
            case '\\': c = '\\'; break;
            case 'u': {
                // only the basic multilingual plane below 0x800 is decoded to
                // utf-8 here; surrogate pairs are passed through as '?' since
                // nothing in a disk diagnostic needs them. (satoru)
                unsigned v = 0;
                for (int i = 1; i <= 4 && p[i]; i++) {
                    char h = p[i];
                    v <<= 4;
                    if (h >= '0' && h <= '9') v |= (unsigned)(h - '0');
                    else if (h >= 'a' && h <= 'f') v |= (unsigned)(h - 'a' + 10);
                    else if (h >= 'A' && h <= 'F') v |= (unsigned)(h - 'A' + 10);
                }
                p += 4;
                if (v < 0x80) {
                    char b1 = (char)v;
                    buf_add(&out, &b1, 1);
                } else if (v < 0x800) {
                    char u2[2];
                    u2[0] = (char)(0xC0 | (v >> 6));
                    u2[1] = (char)(0x80 | (v & 0x3F));
                    buf_add(&out, u2, 2);
                } else {
                    char u3[3];
                    u3[0] = (char)(0xE0 | (v >> 12));
                    u3[1] = (char)(0x80 | ((v >> 6) & 0x3F));
                    u3[2] = (char)(0x80 | (v & 0x3F));
                    buf_add(&out, u3, 3);
                }
                p++;
                continue;
            }
            default: c = *p; break;
            }
            buf_add(&out, &c, 1);
            p++;
            continue;
        }
        buf_add(&out, p, 1);
        p++;
    }
    if (!out.p) buf_add(&out, "", 0);
    return out.p;
}

// ---------------------------------------------------------------- tcp

// connect() on kurono returns EINPROGRESS and completes asynchronously. treat
// that as "keep waiting", not as a failure, and confirm the result with
// SO_ERROR - a poll wakeup alone does not mean the connection succeeded.
// returns 0 on a genuinely established socket. (satoru)
static int connect_finish(int fd)
{
    struct pollfd pfd;
    pfd.fd = fd;
    pfd.events = POLLOUT;
    pfd.revents = 0;
    if (poll(&pfd, 1, 30000) <= 0) return -1;

    int err = 0;
    socklen_t elen = sizeof err;
    if (getsockopt(fd, SOL_SOCKET, SO_ERROR, &err, &elen) < 0) return -1;
    if (err) { errno = err; return -1; }
    return 0;
}

static int try_connect(int fd, const struct sockaddr *sa, socklen_t slen)
{
    if (connect(fd, sa, slen) == 0) return 0;
    if (errno == EINPROGRESS || errno == EALREADY || errno == EAGAIN)
        return connect_finish(fd);
    return -1;
}

static int host_connect(const char *host, const char *port)
{
    const char *ip = getenv("DSAI_HOST_IP");
    if (ip && *ip) {
        struct sockaddr_in sa;
        memset(&sa, 0, sizeof sa);
        sa.sin_family = AF_INET;
        sa.sin_port = htons((unsigned short)atoi(port));
        if (inet_pton(AF_INET, ip, &sa.sin_addr) != 1) {
            fprintf(stderr, "dsai: DSAI_HOST_IP is not a valid ipv4\n");
            return -1;
        }
        int fd = socket(AF_INET, SOCK_STREAM, 0);
        if (fd < 0) return -1;
        if (try_connect(fd, (struct sockaddr *)&sa, sizeof sa) < 0) {
            fprintf(stderr, "dsai: connect %s:%s failed: %s\n",
                    ip, port, strerror(errno));
            close(fd);
            return -1;
        }
        return fd;
    }

    struct addrinfo hints, *ai = NULL, *p;
    memset(&hints, 0, sizeof hints);
    hints.ai_family = AF_UNSPEC;
    hints.ai_socktype = SOCK_STREAM;
    int rc = getaddrinfo(host, port, &hints, &ai);
    if (rc) {
        fprintf(stderr, "dsai: dns lookup of %s failed: %s\n"
                        "      (set DSAI_HOST_IP=<ip> to skip dns)\n",
                host, gai_strerror(rc));
        return -1;
    }
    int fd = -1;
    for (p = ai; p; p = p->ai_next) {
        fd = socket(p->ai_family, p->ai_socktype, p->ai_protocol);
        if (fd < 0) continue;
        if (try_connect(fd, p->ai_addr, p->ai_addrlen) == 0) break;
        close(fd);
        fd = -1;
    }
    freeaddrinfo(ai);
    if (fd < 0) {
        fprintf(stderr, "dsai: could not connect to %s:%s\n", host, port);
        return -1;
    }
    int one = 1;
    setsockopt(fd, IPPROTO_TCP, TCP_NODELAY, &one, sizeof one);
    return fd;
}

// KURONO'S SOCKETS ARE NON-BLOCKING. its connect() returns EINPROGRESS and the
// tcp stack finishes the handshake asynchronously, so read()/write() answer
// EAGAIN for a while after connect returns. treating that as fatal is what made
// the first in-vm run die with BR_ERR_IO nine milliseconds after the kernel
// logged "-> ESTABLISHED": the socket was fine, the client gave up on it. wait
// for readiness instead of failing. (satoru)
#define SOCK_WAIT_MS 30000

static int sock_wait(int fd, short ev)
{
    struct pollfd pfd;
    pfd.fd = fd;
    pfd.events = ev;
    pfd.revents = 0;
    int r = poll(&pfd, 1, SOCK_WAIT_MS);
    return r > 0 ? 0 : -1;
}

static int sock_read(void *ctx, unsigned char *b, size_t len)
{
    int fd = *(int *)ctx;
    for (;;) {
        ssize_t n = read(fd, b, len);
        if (n > 0) return (int)n;
        if (n == 0) return -1;                       // peer closed
        if (errno == EINTR) continue;
        if (errno == EAGAIN || errno == EWOULDBLOCK) {
            if (sock_wait(fd, POLLIN) < 0) {
                fprintf(stderr, "dsai: timed out waiting for data\n");
                return -1;
            }
            continue;
        }
        fprintf(stderr, "dsai: socket read failed: %s\n", strerror(errno));
        return -1;
    }
}

static int sock_write(void *ctx, const unsigned char *b, size_t len)
{
    int fd = *(int *)ctx;
    for (;;) {
        ssize_t n = write(fd, b, len);
        if (n > 0) return (int)n;
        if (n == 0) return -1;
        if (errno == EINTR) continue;
        if (errno == EAGAIN || errno == EWOULDBLOCK || errno == ENOTCONN) {
            if (sock_wait(fd, POLLOUT) < 0) {
                fprintf(stderr, "dsai: timed out waiting to send\n");
                return -1;
            }
            continue;
        }
        fprintf(stderr, "dsai: socket write failed: %s\n", strerror(errno));
        return -1;
    }
}

// bearssl will not hand out a handshake until its prng has entropy. on a normal
// linux box the built-in system seeder handles it; on a freshly booted rescue
// kernel /dev/urandom may be thin, so mix in the clock and the tsc as well.
// this is belt-and-braces, not a substitute for a real entropy source. (satoru)
static void seed_entropy(br_ssl_client_context *sc)
{
    unsigned char seed[64];
    size_t have = 0;
    int fd = open("/dev/urandom", O_RDONLY);
    if (fd >= 0) {
        ssize_t n = read(fd, seed, sizeof seed);
        if (n > 0) have = (size_t)n;
        close(fd);
    }
    if (have < sizeof seed) {
        struct timespec ts;
        clock_gettime(CLOCK_REALTIME, &ts);
        unsigned long long tsc = 0;
#if defined(__x86_64__)
        unsigned int lo, hi;
        __asm__ __volatile__("rdtsc" : "=a"(lo), "=d"(hi));
        tsc = ((unsigned long long)hi << 32) | lo;
#endif
        unsigned long long mix[4];
        mix[0] = (unsigned long long)ts.tv_sec;
        mix[1] = (unsigned long long)ts.tv_nsec;
        mix[2] = tsc;
        mix[3] = (unsigned long long)getpid();
        size_t room = sizeof seed - have;
        size_t take = room < sizeof mix ? room : sizeof mix;
        memcpy(seed + have, mix, take);
        have += take;
    }
    br_ssl_engine_inject_entropy(&sc->eng, seed, have);
}

// ---------------------------------------------------------------- https

typedef struct {
    int fd;
    br_ssl_client_context sc;
    br_x509_minimal_context xc;
    unsigned char iobuf[BR_SSL_BUFSIZE_BIDI];
    br_sslio_context ioc;
} tls_t;

static int tls_open(tls_t *t, const char *host)
{
    t->fd = host_connect(host, DS_PORT);
    if (t->fd < 0) return -1;

    br_ssl_client_init_full(&t->sc, &t->xc, TAs, TAs_NUM);

    // pin the validation clock explicitly. left unset, bearssl falls back to
    // time() and a machine with a dead or unset rtc fails the handshake with
    // BR_ERR_X509_EXPIRED / NOT_YET_VALID - which reads as "their certificate
    // is broken" and sends you hunting in completely the wrong place. a rescue
    // box booted off a cd is exactly where a bogus clock is likely, so check it
    // here and say so plainly. (satoru)
    {
        time_t now = time(NULL);
        if (now < 1735689600L) {          // 2025-01-01
            fprintf(stderr,
                "dsai: system clock reads %ld, which is implausible.\n"
                "      tls certificate validation needs a roughly correct date;\n"
                "      set the clock and retry if the handshake fails.\n",
                (long)now);
        }
        uint32_t days = (uint32_t)(now / 86400) + 719528u;  // unix epoch -> year 0
        uint32_t secs = (uint32_t)(now % 86400);
        br_x509_minimal_set_time(&t->xc, days, secs);
    }

    seed_entropy(&t->sc);
    br_ssl_engine_set_buffer(&t->sc.eng, t->iobuf, sizeof t->iobuf, 1);
    if (!br_ssl_client_reset(&t->sc, host, 0)) {
        fprintf(stderr, "dsai: tls reset failed\n");
        close(t->fd);
        return -1;
    }
    br_sslio_init(&t->ioc, &t->sc.eng, sock_read, &t->fd, sock_write, &t->fd);
    return 0;
}

static void tls_close(tls_t *t)
{
    close(t->fd);
    t->fd = -1;
}

static int tls_write_all(tls_t *t, const char *s, size_t n)
{
    return br_sslio_write_all(&t->ioc, s, n) < 0 ? -1 : 0;
}

// read the whole response. deepseek answers non-streaming requests with
// transfer-encoding: chunked, so both framings are handled. (satoru)
static int https_read_response(tls_t *t, buf_t *out, int *status)
{
    buf_t raw;
    buf_init(&raw);
    unsigned char tmp[2048];

    // headers first
    const char *hdr_end = NULL;
    for (;;) {
        int n = br_sslio_read(&t->ioc, tmp, sizeof tmp);
        if (n < 0) break;
        if (buf_add(&raw, (const char *)tmp, (size_t)n) < 0) { buf_free(&raw); return -1; }
        hdr_end = strstr(raw.p, "\r\n\r\n");
        if (hdr_end) break;
    }
    if (!hdr_end) {
        fprintf(stderr, "dsai: connection closed before headers arrived\n");
        buf_free(&raw);
        return -1;
    }

    *status = 0;
    if (!strncmp(raw.p, "HTTP/1.", 7)) *status = atoi(raw.p + 9);

    size_t hlen = (size_t)(hdr_end - raw.p) + 4;
    // header names are case-insensitive; deepseek sends lowercase but do not
    // rely on that (satoru)
    int chunked = 0;
    long clen = -1;
    {
        char *h = malloc(hlen + 1);
        if (!h) { buf_free(&raw); return -1; }
        for (size_t i = 0; i < hlen; i++) h[i] = (char)tolower((unsigned char)raw.p[i]);
        h[hlen] = 0;
        if (strstr(h, "transfer-encoding: chunked")) chunked = 1;
        char *cl = strstr(h, "content-length:");
        if (cl) clen = atol(cl + 15);
        free(h);
    }

    buf_t body;
    buf_init(&body);
    if (buf_add(&body, raw.p + hlen, raw.len - hlen) < 0) {
        buf_free(&raw); buf_free(&body); return -1;
    }
    buf_free(&raw);

    // pull the rest
    for (;;) {
        if (!chunked && clen >= 0 && body.len >= (size_t)clen) break;
        int n = br_sslio_read(&t->ioc, tmp, sizeof tmp);
        if (n < 0) break;
        if (buf_add(&body, (const char *)tmp, (size_t)n) < 0) { buf_free(&body); return -1; }
        if (chunked && body.len >= 5 &&
            !memcmp(body.p + body.len - 5, "0\r\n\r\n", 5)) break;
    }

    if (!chunked) { *out = body; return 0; }

    // de-chunk
    buf_t dec;
    buf_init(&dec);
    const char *p = body.p;
    const char *end = body.p + body.len;
    while (p < end) {
        char *stop = NULL;
        long sz = strtol(p, &stop, 16);
        if (!stop || stop == p || sz < 0) break;
        p = strstr(stop, "\r\n");
        if (!p) break;
        p += 2;
        if (sz == 0) break;
        if (p + sz > end) sz = (long)(end - p);
        if (buf_add(&dec, p, (size_t)sz) < 0) { buf_free(&body); buf_free(&dec); return -1; }
        p += sz;
        if (p + 2 <= end && !memcmp(p, "\r\n", 2)) p += 2;
    }
    buf_free(&body);
    *out = dec;
    return 0;
}

// one full request/response. a fresh connection per turn: the tool loop is
// low-rate and human-paced, so connection reuse buys nothing and a stale
// half-closed socket on a flaky rescue network costs a confusing retry. (satoru)
static int https_post(const char *host, const char *path, const char *apikey,
                      const char *json, buf_t *out, int *status)
{
    tls_t t;
    if (tls_open(&t, host) < 0) return -1;

    buf_t req;
    buf_init(&req);
    char hdr[512];
    snprintf(hdr, sizeof hdr,
             "POST %s HTTP/1.1\r\n"
             "Host: %s\r\n"
             "User-Agent: kurono-dsai/1.0\r\n"
             "Content-Type: application/json\r\n"
             "Authorization: Bearer %s\r\n"
             "Accept: application/json\r\n"
             "Connection: close\r\n"
             "Content-Length: %zu\r\n\r\n",
             path, host, apikey, strlen(json));
    buf_puts(&req, hdr);
    buf_puts(&req, json);

    int rc = tls_write_all(&t, req.p, req.len);
    if (rc == 0) rc = br_sslio_flush(&t.ioc) < 0 ? -1 : 0;
    buf_free(&req);

    if (rc < 0) {
        fprintf(stderr, "dsai: tls write failed (err %d)\n",
                br_ssl_engine_last_error(&t.sc.eng));
        tls_close(&t);
        return -1;
    }

    rc = https_read_response(&t, out, status);
    int eng_err = br_ssl_engine_last_error(&t.sc.eng);
    tls_close(&t);
    if (rc < 0 && eng_err != BR_ERR_OK)
        fprintf(stderr, "dsai: tls error %d\n", eng_err);
    return rc;
}

// ---------------------------------------------------------------- tools

// commands whose worst case is a wasted second. anything not on this list is
// treated as capable of touching the patient disk and needs a human yes.
// matched on the first token only, and re-checked for shell metacharacters
// below so "lsblk; mkfs /dev/sda" cannot sneak through. (satoru)
static const char *READONLY_CMDS[] = {
    "lsblk", "blkid", "df", "ls", "cat", "head", "tail", "file", "stat",
    "dmesg", "uname", "mount", "findmnt", "free", "ps", "lspci", "lsusb",
    "smartctl", "wc", "grep", "readlink", "id", "date", "hostname", "ip",
    NULL
};

static int cmd_is_readonly(const char *cmd)
{
    while (*cmd == ' ' || *cmd == '\t') cmd++;

    // any shell metacharacter means we cannot reason about what actually runs,
    // so it goes to the operator regardless of how it starts (satoru)
    for (const char *p = cmd; *p; p++)
        if (strchr(";|&><`$\n", *p)) return 0;

    size_t n = 0;
    while (cmd[n] && cmd[n] != ' ' && cmd[n] != '\t') n++;

    // reject a path-qualified binary: /sbin/mkfs would otherwise never match
    // the list and be correctly refused, but ./cat would wrongly match (satoru)
    for (size_t i = 0; i < n; i++)
        if (cmd[i] == '/') return 0;

    for (int i = 0; READONLY_CMDS[i]; i++) {
        size_t l = strlen(READONLY_CMDS[i]);
        if (l == n && !memcmp(cmd, READONLY_CMDS[i], l)) {
            // a couple of read-only-by-default tools have destructive flags
            if (!memcmp(cmd, "mount", 5) && strstr(cmd, "-o remount")) return 0;
            return 1;
        }
    }
    return 0;
}

static int ask_operator(const char *cmd)
{
    const char *yes = getenv("DSAI_YES");
    if (yes && *yes == '1') {
        printf("  [auto-approved by DSAI_YES] %s\n", cmd);
        return 1;
    }
    printf("\n  the model wants to run a command that is not read-only:\n"
           "      %s\n"
           "  allow it? [y/N] ", cmd);
    fflush(stdout);
    char line[64];
    if (!fgets(line, sizeof line, stdin)) return 0;
    return line[0] == 'y' || line[0] == 'Y';
}

// run a command and capture combined output, capped so one chatty tool cannot
// blow the context window (satoru)
// kurono has no /bin/sh, so popen() cannot work there. the kernel exposes
// /dev/kshell instead: write a command line, read back what it printed. try it
// first so one binary runs unchanged on both the rescue kernel and a host
// linux box, and fall through to popen when the device is absent. (satoru)
static char *run_capture_kshell(const char *cmd, size_t cap)
{
    int fd = open("/dev/kshell", O_RDWR);
    if (fd < 0) return NULL;

    size_t len = strlen(cmd);
    if (write(fd, cmd, len) != (ssize_t)len) { close(fd); return NULL; }

    buf_t out;
    buf_init(&out);
    char tmp[1024];
    for (;;) {
        ssize_t n = read(fd, tmp, sizeof tmp);
        if (n <= 0) break;
        if (out.len >= cap) { buf_puts(&out, "\n... (output truncated)\n"); break; }
        if (out.len + (size_t)n > cap) n = (ssize_t)(cap - out.len);
        buf_add(&out, tmp, (size_t)n);
    }
    close(fd);
    if (!out.p) return strdup("(no output)");
    return out.p;
}

static char *run_capture(const char *cmd, size_t cap)
{
    char *k = run_capture_kshell(cmd, cap);
    if (k) return k;

    buf_t full;
    buf_init(&full);
    buf_puts(&full, cmd);
    buf_puts(&full, " 2>&1");

    FILE *f = popen(full.p, "r");
    buf_free(&full);
    if (!f) return strdup("(failed to start command)");

    buf_t out;
    buf_init(&out);
    char tmp[1024];
    size_t n;
    int truncated = 0;
    while ((n = fread(tmp, 1, sizeof tmp, f)) > 0) {
        if (out.len >= cap) { truncated = 1; continue; }
        if (out.len + n > cap) n = cap - out.len;
        buf_add(&out, tmp, n);
    }
    int rc = pclose(f);
    if (truncated) buf_puts(&out, "\n... (output truncated)\n");
    char tail[64];
    snprintf(tail, sizeof tail, "\n(exit status %d)\n", WEXITSTATUS(rc));
    buf_puts(&out, tail);
    if (!out.p) return strdup("(no output)");
    return out.p;
}

static char *tool_run_cmd(const char *args_json)
{
    const char *v = json_find(args_json, "cmd");
    char *cmd = json_str_dup(v);
    if (!cmd) return strdup("error: missing \"cmd\" argument");

    printf("  $ %s\n", cmd);
    if (!cmd_is_readonly(cmd) && !ask_operator(cmd)) {
        free(cmd);
        return strdup("refused by operator: this command was not run. "
                      "suggest a read-only alternative, or explain to the "
                      "operator exactly what it would change and why.");
    }
    char *out = run_capture(cmd, 8000);
    free(cmd);
    return out;
}

static char *tool_read_file(const char *args_json)
{
    const char *v = json_find(args_json, "path");
    char *path = json_str_dup(v);
    if (!path) return strdup("error: missing \"path\" argument");

    printf("  read %s\n", path);
    FILE *f = fopen(path, "rb");
    if (!f) {
        char msg[512];
        snprintf(msg, sizeof msg, "cannot open %s: %s", path, strerror(errno));
        free(path);
        return strdup(msg);
    }
    free(path);
    buf_t out;
    buf_init(&out);
    char tmp[1024];
    size_t n;
    while ((n = fread(tmp, 1, sizeof tmp, f)) > 0) {
        if (out.len >= 16000) { buf_puts(&out, "\n... (truncated)\n"); break; }
        buf_add(&out, tmp, n);
    }
    fclose(f);
    if (!out.p) return strdup("(empty file)");
    return out.p;
}

// the tool schema the model is given. json mode and tool calling are mutually
// exclusive in this api, so requests that carry this must NOT also carry a
// response_format field. (satoru)
static const char *TOOLS_JSON =
"[{\"type\":\"function\",\"function\":{"
  "\"name\":\"run_cmd\","
  "\"description\":\"Run a single diagnostic command on the rescue system. "
    "IMPORTANT: there is no shell. Pipes, redirection, ; && || and 2>&1 are "
    "always REJECTED, and stderr is already included in what you get back, so "
    "write a bare command such as 'lsblk' or 'cat /proc/partitions' and nothing "
    "more. Read-only diagnostics run immediately; anything that could modify a "
    "disk needs the operator to approve it first, so prefer inspection over "
    "repair and explain your reasoning before acting.\","
  "\"parameters\":{\"type\":\"object\",\"properties\":{"
    "\"cmd\":{\"type\":\"string\",\"description\":\"The command line to run.\"}},"
    "\"required\":[\"cmd\"]}}},"
"{\"type\":\"function\",\"function\":{"
  "\"name\":\"read_file\","
  "\"description\":\"Read a file from the rescue system or a mounted patient "
    "filesystem. Truncated at 16 KB.\","
  "\"parameters\":{\"type\":\"object\",\"properties\":{"
    "\"path\":{\"type\":\"string\",\"description\":\"Absolute path to read.\"}},"
    "\"required\":[\"path\"]}}}]";

static const char *SYSTEM_PROMPT =
"You are the recovery assistant built into Kurono OS, a from-scratch bare-metal "
"operating system being used as a rescue environment. The operator has booted "
"you because their machine will not start. "
"Work like a careful engineer: inspect before you conclude, and say plainly "
"when the evidence is thin rather than guessing. Use run_cmd to gather real "
"facts about the disks, filesystems and boot configuration instead of "
"speculating. "
"Never propose a destructive action (mkfs, dd to a device, fdisk writes, "
"forced fsck) without first stating what it will destroy and what the "
"alternative is. Prefer read-only diagnosis; the operator must approve "
"anything that writes. "
"Keep answers short and concrete. The operator is at a serial console. "
"There is no shell: run one bare command per tool call, with no pipes, no "
"redirection and no 2>&1 - those are rejected and waste a turn.";

// ---------------------------------------------------------------- key loading

static char *load_api_key(void)
{
    const char *env = getenv("DEEPSEEK_API_KEY");
    if (env && *env) return strdup(env);

    // /etc/deepseek.key is where the kurono image drops the baked-in key;
    // /var/tmp is the host default. (satoru)
    static const char *CANDIDATES[] = {
        "/etc/deepseek.key", "/var/tmp/deepseek.key", NULL
    };
    const char *path = getenv("DEEPSEEK_KEY_FILE");
    struct stat st;
    if (!path || !*path) {
        path = NULL;
        for (int i = 0; CANDIDATES[i]; i++)
            if (stat(CANDIDATES[i], &st) == 0) { path = CANDIDATES[i]; break; }
        if (!path) {
            fprintf(stderr, "dsai: no api key. set DEEPSEEK_API_KEY, or put it "
                            "in /etc/deepseek.key\n");
            return NULL;
        }
    }

    if (stat(path, &st) < 0) {
        fprintf(stderr,
                "dsai: no api key. set DEEPSEEK_API_KEY, or put it in %s\n",
                path);
        return NULL;
    }
    // only meaningful on a filesystem that HAS a permission model. kurono's
    // kvfs reports a permissive fixed mode for every file, so this fired on
    // every rescue boot and told the operator their api key was world-readable
    // when nothing of the sort had happened - the kind of false alarm that gets
    // someone rotating credentials in the middle of a recovery. skip the check
    // for the image-installed path, where the mode carries no information.
    // (satoru)
    if (strcmp(path, "/etc/deepseek.key") != 0 &&
        (st.st_mode & (S_IRWXG | S_IRWXO)))
        fprintf(stderr, "dsai: warning: %s is readable by other users\n", path);

    FILE *f = fopen(path, "r");
    if (!f) {
        fprintf(stderr, "dsai: cannot open %s: %s\n", path, strerror(errno));
        return NULL;
    }
    char line[512];
    if (!fgets(line, sizeof line, f)) { fclose(f); return NULL; }
    fclose(f);
    size_t n = strlen(line);
    while (n && (line[n-1] == '\n' || line[n-1] == '\r' || line[n-1] == ' ')) line[--n] = 0;
    if (!n) {
        fprintf(stderr, "dsai: %s is empty\n", path);
        return NULL;
    }
    return strdup(line);
}

// ---------------------------------------------------------------- main loop

int main(int argc, char **argv)
{
    setvbuf(stdout, NULL, _IOLBF, 0);

    char *apikey = load_api_key();
    if (!apikey) return 1;

    const char *model = getenv("DSAI_MODEL");
    if (!model || !*model) model = "deepseek-v4-pro";

    // the whole question, from argv, so this works from a one-shot rescue shell
    buf_t question;
    buf_init(&question);
    for (int i = 1; i < argc; i++) {
        if (i > 1) buf_puts(&question, " ");
        buf_puts(&question, argv[i]);
    }
    if (!question.len) {
        printf("kurono recovery assistant. describe the problem: ");
        fflush(stdout);
        char line[2048];
        if (!fgets(line, sizeof line, stdin)) return 1;
        buf_puts(&question, line);
    }

    // conversation history, accumulated as raw json message objects (satoru)
    buf_t msgs;
    buf_init(&msgs);
    buf_puts(&msgs, "{\"role\":\"system\",\"content\":\"");
    buf_json_escape(&msgs, SYSTEM_PROMPT, strlen(SYSTEM_PROMPT));
    buf_puts(&msgs, "\"},{\"role\":\"user\",\"content\":\"");
    buf_json_escape(&msgs, question.p, question.len);
    buf_puts(&msgs, "\"}");
    buf_free(&question);

    int rc = 0;
    for (int turn = 0; turn < MAX_TURNS; turn++) {
        buf_t req;
        buf_init(&req);
        buf_puts(&req, "{\"model\":\"");
        buf_puts(&req, model);
        buf_puts(&req, "\",\"messages\":[");
        buf_add(&req, msgs.p, msgs.len);
        buf_puts(&req, "],\"tools\":");
        buf_puts(&req, TOOLS_JSON);
        // thinking disabled is the large latency win on v4-pro and this is an
        // interactive console tool (satoru)
        buf_puts(&req, ",\"thinking\":{\"type\":\"disabled\"}");
        buf_puts(&req, ",\"temperature\":0.2,\"max_tokens\":2048}");

        buf_t resp;
        buf_init(&resp);
        int status = 0;
        if (https_post(DS_HOST, DS_PATH, apikey, req.p, &resp, &status) < 0) {
            buf_free(&req);
            buf_free(&resp);
            rc = 1;
            break;
        }
        buf_free(&req);

        if (status != 200) {
            fprintf(stderr, "dsai: api returned http %d\n%s\n",
                    status, resp.p ? resp.p : "(no body)");
            buf_free(&resp);
            rc = 1;
            break;
        }

        const char *msg = json_find(resp.p, "message");
        if (!msg) {
            fprintf(stderr, "dsai: unexpected response shape\n%s\n", resp.p);
            buf_free(&resp);
            rc = 1;
            break;
        }

        const char *tc = json_find(msg, "tool_calls");
        if (!tc || *tc != '[') {
            char *content = json_str_dup(json_find(msg, "content"));
            printf("\n%s\n", content ? content : "(empty reply)");
            free(content);
            buf_free(&resp);
            break;
        }

        // the assistant turn has to go back verbatim, tool_calls and all, or
        // the api rejects the following tool results as unsolicited (satoru)
        const char *msg_end = json_skip_value(msg);
        buf_puts(&msgs, ",");
        buf_add(&msgs, msg, (size_t)(msg_end - msg));

        // walk the tool_calls array
        const char *p = tc + 1;
        int ncalls = 0;
        for (;;) {
            p = json_skip_ws(p);
            if (*p != '{') break;
            const char *elem_end = json_skip_value(p);
            if (ncalls >= MAX_TOOLCALLS) break;

            char *id   = json_str_dup(json_find(p, "id"));
            const char *fn = json_find(p, "function");
            char *name = fn ? json_str_dup(json_find(fn, "name")) : NULL;
            char *args = fn ? json_str_dup(json_find(fn, "arguments")) : NULL;

            char *result = NULL;
            if (!name) {
                result = strdup("error: malformed tool call");
            } else if (!strcmp(name, "run_cmd")) {
                result = tool_run_cmd(args ? args : "{}");
            } else if (!strcmp(name, "read_file")) {
                result = tool_read_file(args ? args : "{}");
            } else {
                char m[256];
                snprintf(m, sizeof m, "error: no such tool \"%s\"", name);
                result = strdup(m);
            }

            buf_puts(&msgs, ",{\"role\":\"tool\",\"tool_call_id\":\"");
            if (id) buf_json_escape(&msgs, id, strlen(id));
            buf_puts(&msgs, "\",\"content\":\"");
            buf_json_escape(&msgs, result, strlen(result));
            buf_puts(&msgs, "\"}");

            free(id); free(name); free(args); free(result);
            ncalls++;

            p = json_skip_ws(elem_end);
            if (*p == ',') { p++; continue; }
            break;
        }
        buf_free(&resp);

        if (!ncalls) {
            fprintf(stderr, "dsai: tool_calls present but none parsed\n");
            rc = 1;
            break;
        }
        if (turn == MAX_TURNS - 1)
            fprintf(stderr, "dsai: hit the %d-turn tool limit\n", MAX_TURNS);
    }

    buf_free(&msgs);
    free(apikey);
    return rc;
}

