// dsai - the ai recovery client for the kurono rescue environment (satoru)
//
// talks to the deepseek chat-completions api over tls and runs a tool loop so
// the model can inspect the broken machine (block devices, filesystems, logs)
// and propose repairs. built musl-static against bearssl so it drops into a
// rescue image with no shared-library surface at all.
//
// safety model: read-only diagnostics run automatically, anything that could
// write to the patient disk stops and asks the operator first. a recovery tool
// that silently mutates a damaged filesystem is worse than no tool. (satoru)
//
//   cc -static -o dsai dsai.c -lbearssl
//
// env:
//   DEEPSEEK_API_KEY   required, or DEEPSEEK_KEY_FILE pointing at a 0600 file
//   DSAI_MODEL         default deepseek-v4-pro
//   DSAI_HOST_IP       skip dns and dial this ip (rescue nets often lack dns)
//   DSAI_YES           set to 1 to auto-approve write commands (dangerous)

