#!/usr/bin/env python3
# generate kf_tas.h (bearssl trust anchors) for kfetch from pem roots. (satoru)
# usage: gen_kf_tas.py root1.crt root2.crt ... > kf_tas.h
# only the roots that downloads.claude.ai can chain to are used: the google
# trust services roots (the bucket's issuer family) plus globalsign root ca,
# which cross-signs gts root r1. (satoru)
import sys
from cryptography import x509
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa, ec

def arr(name, data):
    out = ["static const unsigned char %s[] = {" % name]
    for i in range(0, len(data), 12):
        out.append("\t" + ", ".join("0x%02X" % b for b in data[i:i + 12]) + ("," if i + 12 < len(data) else ""))
    out.append("};\n")
    return "\n".join(out)

certs = []
for p in sys.argv[1:]:
    certs.append(x509.load_pem_x509_certificate(open(p, "rb").read()))
print("// generated by gen_kf_tas.py, do not edit (satoru)")
for i, c in enumerate(certs):
    print(arr("KTA%d_DN" % i, c.subject.public_bytes()))
    k = c.public_key()
    if isinstance(k, rsa.RSAPublicKey):
        n = k.public_numbers()
        nb = n.n.to_bytes((n.n.bit_length() + 7) // 8, "big")
        eb = n.e.to_bytes((n.e.bit_length() + 7) // 8, "big")
        print(arr("KTA%d_RSA_N" % i, nb))
        print(arr("KTA%d_RSA_E" % i, eb))
    else:
        q = k.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
        print(arr("KTA%d_EC_Q" % i, q))
print("static const br_x509_trust_anchor TAs[] = {")
for i, c in enumerate(certs):
    k = c.public_key()
    print("\t{ { (unsigned char *)KTA%d_DN, sizeof KTA%d_DN }, BR_X509_TA_CA, {" % (i, i))
    if isinstance(k, rsa.RSAPublicKey):
        print("\t\tBR_KEYTYPE_RSA, { .rsa = { (unsigned char *)KTA%d_RSA_N, sizeof KTA%d_RSA_N, (unsigned char *)KTA%d_RSA_E, sizeof KTA%d_RSA_E } } } }%s" % (i, i, i, i, ","))
    else:
        cid = {"secp256r1": "BR_EC_secp256r1", "secp384r1": "BR_EC_secp384r1", "secp521r1": "BR_EC_secp521r1"}[k.curve.name]
        print("\t\tBR_KEYTYPE_EC, { .ec = { %s, (unsigned char *)KTA%d_EC_Q, sizeof KTA%d_EC_Q } } } }%s" % (cid, i, i, ","))
print("};\n\n#define TAs_NUM %d\n// end (satoru)" % len(certs))
