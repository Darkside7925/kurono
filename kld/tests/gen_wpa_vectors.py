#!/usr/bin/env python3
# gen_wpa_vectors.py - independent-oracle vectors for apitest_wpa.c.
#
# PMK, PTK (PRF-SHA1 and KDF-SHA256), EAPOL-Key MIC (descriptor versions 2 and
# 3) and RFC 3394 unwrap are computed here with python hashlib/hmac and
# python-cryptography, not with any kernel code. fixed seed, checked in.
#
#   python3 kld/tests/gen_wpa_vectors.py > kld/tests/wpa_vectors.h
#
# end (satoru)

import hashlib
import hmac
import random
import struct
import sys

from cryptography.hazmat.primitives import cmac, hashes
from cryptography.hazmat.primitives.ciphers import algorithms
from cryptography.hazmat.primitives.keywrap import aes_key_wrap

RNG = random.Random(0x77706132)  # "wpa2" (satoru)


def rb(n):
    return bytes(RNG.getrandbits(8) for _ in range(n))


def cinit(values, per_line=12):
    if not values:
        return '0'
    chunks = []
    for i in range(0, len(values), per_line):
        chunks.append(', '.join('0x%02x' % v for v in values[i:i + per_line]))
    return ',\n        '.join(chunks)


def prf_sha1(key, label, data, out_len):
    out = b''
    counter = 0
    while len(out) < out_len:
        out += hmac.new(key, label.encode() + b'\0' + data + bytes([counter]),
                        hashlib.sha1).digest()
        counter += 1
    return out[:out_len]


def kdf_sha256(key, label, data, out_len):
    out = b''
    counter = 1
    while len(out) < out_len:
        msg = (struct.pack('<H', counter) + label.encode() + data +
               struct.pack('<H', out_len * 8))
        out += hmac.new(key, msg, hashlib.sha256).digest()
        counter += 1
    return out[:out_len]


def emit(out):
    out.write('// AUTO-GENERATED by kld/tests/gen_wpa_vectors.py - do not edit.\n')
    out.write('// python hashlib/hmac and cryptography 43.0.0, fixed seed. (satoru)\n')
    out.write('#ifndef KLD_WPA_VECTORS_H\n#define KLD_WPA_VECTORS_H\n\n')

    out.write('struct wv_pmk_vec {\n')
    out.write('    unsigned char pass[64];\n    unsigned int pass_len;\n')
    out.write('    unsigned char ssid[32];\n    unsigned int ssid_len;\n')
    out.write('    unsigned char pmk[32];\n};\n\n')
    out.write('struct wv_ptk_vec {\n')
    out.write('    unsigned char pmk[32];\n    unsigned char aa[6];\n')
    out.write('    unsigned char spa[6];\n    unsigned char anonce[32];\n')
    out.write('    unsigned char snonce[32];\n    unsigned int akm;\n')
    out.write('    unsigned char ptk[48];\n};\n\n')
    out.write('struct wv_mic_vec {\n')
    out.write('    unsigned char kck[16];\n    unsigned char frame[192];\n')
    out.write('    unsigned int frame_len;\n    unsigned int ver;\n')
    out.write('    unsigned char mic[16];\n};\n\n')
    out.write('struct wv_unwrap_vec {\n')
    out.write('    unsigned char kek[16];\n    unsigned char wrapped[40];\n')
    out.write('    unsigned int wrapped_len;\n    unsigned char pt[32];\n')
    out.write('    unsigned int pt_len;\n};\n\n')

    # ---- pmk: the standard's known answer then five random ones (satoru) ----
    pmks = [('password', 'IEEE')]
    alphabet = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789'
    for _ in range(5):
        plen = RNG.randrange(8, 64)
        passwd = ''.join(RNG.choice(alphabet) for _ in range(plen))
        slen = RNG.randrange(1, 33)
        ssid = bytes(RNG.choice(alphabet.encode()) for _ in range(slen))
        pmks.append((passwd, ssid))
    out.write('#define WV_PMK_N %d\n' % len(pmks))
    for i, (passwd, ssid) in enumerate(pmks):
        if isinstance(ssid, str):
            ssid = ssid.encode()
        pmk = hashlib.pbkdf2_hmac('sha1', passwd.encode(), ssid, 4096, 32)
        out.write('static const struct wv_pmk_vec wv_pmk_%d = {\n' % i)
        out.write('    {%s}, %d,\n    {%s}, %d,\n    {%s}\n};\n\n' % (
            cinit(passwd.encode()), len(passwd), cinit(ssid), len(ssid),
            cinit(pmk)))
    out.write('static const struct wv_pmk_vec *const wv_pmk[WV_PMK_N] = {\n')
    out.write(',\n'.join('    &wv_pmk_%d' % i for i in range(len(pmks))))
    out.write('\n};\n\n')

    # ---- ptk: five akm 2 and five akm 6 (satoru) ----
    out.write('#define WV_PTK_N 10\n')
    for i in range(10):
        akm = 2 if i < 5 else 6
        pmk = rb(32)
        aa = rb(6)
        spa = rb(6)
        anonce = rb(32)
        snonce = rb(32)
        data = (min(aa, spa) + max(aa, spa) + min(anonce, snonce) +
                max(anonce, snonce))
        if akm == 2:
            ptk = prf_sha1(pmk, 'Pairwise key expansion', data, 48)
        else:
            ptk = kdf_sha256(pmk, 'Pairwise key expansion', data, 48)
        out.write('static const struct wv_ptk_vec wv_ptk_%d = {\n' % i)
        out.write('    {%s},\n    {%s},\n    {%s},\n    {%s},\n    {%s},\n' % (
            cinit(pmk), cinit(aa), cinit(spa), cinit(anonce), cinit(snonce)))
        out.write('    %d,\n    {%s}\n};\n\n' % (akm, cinit(ptk)))
    out.write('static const struct wv_ptk_vec *const wv_ptk[WV_PTK_N] = {\n')
    out.write(',\n'.join('    &wv_ptk_%d' % i for i in range(10)))
    out.write('\n};\n\n')

    # ---- full eapol-key frames, mic zeroed, both descriptor versions ----
    out.write('#define WV_MIC_N 10\n')
    for i in range(10):
        ver = 2 if i < 5 else 3
        kck = rb(16)
        kd_len = RNG.choice((0, 8, 16, 24, 32, 48, 64))
        frame = bytearray(99 + kd_len)
        frame[0] = 2
        frame[1] = 3
        struct.pack_into('>H', frame, 2, len(frame) - 4)
        frame[4] = 2
        key_info = ver | 0x0008 | 0x0100
        if i & 1:
            key_info |= 0x0200
        struct.pack_into('>H', frame, 5, key_info)
        frame[9:17] = rb(8)
        frame[17:49] = rb(32)
        frame[49:65] = rb(16)
        frame[65:73] = rb(8)
        frame[73:81] = rb(8)
        struct.pack_into('>H', frame, 97, kd_len)
        frame[99:99 + kd_len] = rb(kd_len)
        # mic field (81..97) stays zero here
        if ver == 2:
            mic = hmac.new(kck, bytes(frame), hashlib.sha1).digest()[:16]
        else:
            c = cmac.CMAC(algorithms.AES(kck))
            c.update(bytes(frame))
            mic = c.finalize()
        out.write('static const struct wv_mic_vec wv_mic_%d = {\n' % i)
        out.write('    {%s},\n    {%s}, %d,\n    %d,\n    {%s}\n};\n\n' % (
            cinit(kck), cinit(bytes(frame)), len(frame), ver, cinit(mic)))
    out.write('static const struct wv_mic_vec *const wv_mic[WV_MIC_N] = {\n')
    out.write(',\n'.join('    &wv_mic_%d' % i for i in range(10)))
    out.write('\n};\n\n')

    # ---- rfc 3394 unwrap, ten random keks (satoru) ----
    out.write('#define WV_UNWRAP_N 10\n')
    for i in range(10):
        kek = rb(16)
        pt = rb(RNG.choice((16, 24, 32)))
        wrapped = aes_key_wrap(kek, pt)
        out.write('static const struct wv_unwrap_vec wv_unwrap_%d = {\n' % i)
        out.write('    {%s},\n    {%s}, %d,\n    {%s}, %d\n};\n\n' % (
            cinit(kek), cinit(wrapped), len(wrapped), cinit(pt), len(pt)))
    out.write('static const struct wv_unwrap_vec *const wv_unwrap[WV_UNWRAP_N] = {\n')
    out.write(',\n'.join('    &wv_unwrap_%d' % i for i in range(10)))
    out.write('\n};\n\n')

    out.write('#endif\n')
    out.write('// end (satoru)\n')


if __name__ == '__main__':
    emit(sys.stdout)

# end (satoru)
