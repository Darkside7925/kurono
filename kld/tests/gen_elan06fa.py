#!/usr/bin/env python3
# gen_elan06fa.py - generate the real ELAN06FA report descriptor and its report
# id/length table for the hidsim model, from the host sysfs.
#
#   python3 kld/tests/gen_elan06fa.py [report_descriptor] > kld/tests/elan06fa_report_descriptor_desc.h
#
# no descriptor byte is typed by hand. the parser is only used to learn the
# report id and total bit size of each input/feature report so the software
# device can answer GET_REPORT with the right length. (satoru)

import sys

DEFAULT = "/sys/bus/hid/devices/0018:04F3:327E.0001/report_descriptor"


def parse(desc):
    i = 0
    usage_page = 0
    report_id = 0
    rsize = 0
    rcount = 0
    bits = {1: {}, 2: {}}
    while i < len(desc):
        b = desc[i]
        i += 1
        if b == 0xfe:
            ln = desc[i]
            i += 1 + ln
            continue
        size = [0, 1, 2, 4][b & 3]
        typ = (b >> 2) & 3
        tag = b >> 4
        if size and i + size > len(desc):
            break
        val = int.from_bytes(desc[i:i + size], "little") if size else 0
        i += size
        if typ == 1:  # global
            if tag == 0:
                usage_page = val
            elif tag == 7:
                rsize = val
            elif tag == 8:
                report_id = val
            elif tag == 9:
                rcount = val
        elif typ == 0:  # main
            if tag in (8, 9, 11):
                t = {8: 1, 9: 2, 11: 2}[tag]
                if tag == 11:
                    t = 2
                bits[t][report_id] = bits[t].get(report_id, 0) + rsize * rcount
    out = []
    for t, name in ((1, "input"), (2, "feature")):
        for rid, nb in sorted(bits[t].items()):
            out.append((t, rid, (nb + 7) // 8 + (1 if rid else 0)))
    return out


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
    desc = open(path, "rb").read()
    reports = parse(desc)
    w = sys.stdout.write
    w("// AUTO-GENERATED by kld/tests/gen_elan06fa.py - do not edit.\n")
    w("// %d bytes from %s. (satoru)\n" % (len(desc), path))
    w("#ifndef KLD_ELAN06FA_REPORT_DESCRIPTOR_H\n")
    w("#define KLD_ELAN06FA_REPORT_DESCRIPTOR_H\n\n")
    w("#define ELAN06FA_REPORT_DESC_LEN %d\n" % len(desc))
    w("static const unsigned char elan06fa_report_desc[ELAN06FA_REPORT_DESC_LEN] = {\n")
    for i in range(0, len(desc), 12):
        w("    " + ", ".join("0x%02x" % x for x in desc[i:i + 12]) + ",\n")
    w("};\n\n")
    w("struct elan06fa_report_len { unsigned char type, id; unsigned int len; };\n")
    w("static const struct elan06fa_report_len elan06fa_reports[] = {\n")
    for t, rid, ln in reports:
        w("    { %d, 0x%02x, %d },\n" % (t, rid, ln))
    w("};\n#define ELAN06FA_REPORT_COUNT %d\n\n" % len(reports))
    w("#endif\n")
    w("// end (satoru)\n")


if __name__ == "__main__":
    main()

# end (satoru)
