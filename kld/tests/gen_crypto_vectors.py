#!/usr/bin/env python3
# gen_crypto_vectors.py - independent-oracle vectors for apitest_crypto.c.
#
# Every expected value here is produced by python-cryptography (a different
# implementation from the kernel one under test), with a fixed seed so the
# generated header is reproducible and can be checked in. the fixed vectors
# from RFC 3610 / NIST / RFC 4493 / RFC 2202 / RFC 4231 / RFC 6229 live in the
# test source itself; this script only adds the random corpus.
#
#   python3 kld/tests/gen_crypto_vectors.py > kld/tests/crypto_vectors.h
#
# end (satoru)

import random
import sys

from cryptography.hazmat.primitives import cmac, hashes, hmac
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms
from cryptography.hazmat.primitives.ciphers.aead import AESCCM, AESGCM
from cryptography.hazmat.primitives.keywrap import aes_key_wrap

RNG = random.Random(0x6b6c6463)  # "kldc" (satoru)


def rb(n):
    return bytes(RNG.getrandbits(8) for _ in range(n))


def cinit(values, per_line=12):
    if not values:
        return '0'
    chunks = []
    for i in range(0, len(values), per_line):
        chunks.append(', '.join('0x%02x' % v for v in values[i:i + per_line]))
    return ',\n        '.join(chunks)


def emit(out):
    out.write('// AUTO-GENERATED by kld/tests/gen_crypto_vectors.py - do not edit.\n')
    out.write('// random corpus from python-cryptography 43.0.0, fixed seed. (satoru)\n')
    out.write('#ifndef KLD_CRYPTO_VECTORS_H\n#define KLD_CRYPTO_VECTORS_H\n\n')

    out.write('struct cv_aead_vec {\n')
    out.write('    unsigned char key[16];\n')
    out.write('    unsigned char iv[16];\n')
    out.write('    unsigned int iv_len;\n')
    out.write('    unsigned char aad[64];\n')
    out.write('    unsigned int aad_len;\n')
    out.write('    unsigned char pt[64];\n')
    out.write('    unsigned int pt_len;\n')
    out.write('    unsigned char ct[64];\n')
    out.write('    unsigned char tag[16];\n')
    out.write('    unsigned int tag_len;\n')
    out.write('};\n\n')

    out.write('struct cv_hash_vec {\n')
    out.write('    unsigned char key[128];\n')
    out.write('    unsigned int key_len;\n')
    out.write('    unsigned char msg[128];\n')
    out.write('    unsigned int msg_len;\n')
    out.write('    unsigned char out[32];\n')
    out.write('    unsigned int out_len;\n')
    out.write('};\n\n')

    out.write('struct cv_arc4_vec {\n')
    out.write('    unsigned char key[32];\n')
    out.write('    unsigned int key_len;\n')
    out.write('    unsigned char out[16];\n')
    out.write('};\n\n')

    out.write('struct cv_unwrap_vec {\n')
    out.write('    unsigned char kek[16];\n')
    out.write('    unsigned char wrapped[40];\n')
    out.write('    unsigned int wrapped_len;\n')
    out.write('    unsigned char pt[32];\n')
    out.write('    unsigned int pt_len;\n')
    out.write('};\n\n')

    # ---- ccm(aes), CCMP shaped: 13 byte nonce, 8 byte tag (satoru) ----
    out.write('#define CV_CCM_N 20\n')
    for i in range(20):
        key = rb(16)
        nonce = rb(13)
        aad = rb(RNG.randrange(1, 33))
        pt = rb(RNG.randrange(0, 65))
        ct = AESCCM(key, tag_length=8).encrypt(nonce, pt, aad)
        out.write('static const struct cv_aead_vec cv_ccm_%d = {\n' % i)
        out.write('    {%s},\n    {%s}, 13,\n    {%s}, %d,\n    {%s}, %d,\n' % (
            cinit(key), cinit(nonce), cinit(aad), len(aad), cinit(pt), len(pt)))
        out.write('    {%s},\n    {%s}, 8\n};\n\n' % (cinit(ct[:-8]), cinit(ct[-8:])))
    out.write('static const struct cv_aead_vec *const cv_ccm[CV_CCM_N] = {\n')
    out.write(',\n'.join('    &cv_ccm_%d' % i for i in range(20)))
    out.write('\n};\n\n')

    # ---- gcm(aes): 12 byte iv, 16 byte tag, a few GMAC (empty pt) (satoru) ----
    out.write('#define CV_GCM_N 20\n')
    for i in range(20):
        key = rb(16)
        iv = rb(12)
        aad = rb(RNG.randrange(0, 33))
        pt = b'' if i % 5 == 4 else rb(RNG.randrange(0, 65))
        ct = AESGCM(key).encrypt(iv, pt, aad)
        out.write('static const struct cv_aead_vec cv_gcm_%d = {\n' % i)
        out.write('    {%s},\n    {%s}, 12,\n    {%s}, %d,\n    {%s}, %d,\n' % (
            cinit(key), cinit(iv), cinit(aad), len(aad), cinit(pt), len(pt)))
        out.write('    {%s},\n    {%s}, 16\n};\n\n' % (cinit(ct[:-16]), cinit(ct[-16:])))
    out.write('static const struct cv_aead_vec *const cv_gcm[CV_GCM_N] = {\n')
    out.write(',\n'.join('    &cv_gcm_%d' % i for i in range(20)))
    out.write('\n};\n\n')

    # ---- cmac(aes) (satoru) ----
    out.write('#define CV_CMAC_N 20\n')
    for i in range(20):
        key = rb(16)
        msg = rb(RNG.randrange(0, 65))
        c = cmac.CMAC(algorithms.AES(key))
        c.update(msg)
        mac = c.finalize()
        out.write('static const struct cv_hash_vec cv_cmac_%d = {\n' % i)
        out.write('    {%s}, 16,\n    {%s}, %d,\n    {%s}, 16\n};\n\n' % (
            cinit(key), cinit(msg), len(msg), cinit(mac)))
    out.write('static const struct cv_hash_vec *const cv_cmac[CV_CMAC_N] = {\n')
    out.write(',\n'.join('    &cv_cmac_%d' % i for i in range(20)))
    out.write('\n};\n\n')

    # ---- hmac(sha1) and hmac(sha256) (satoru) ----
    for h, n, tag in ((hashes.SHA1(), 'CV_HMAC_SHA1_N', 'cv_hmac_sha1'),
                      (hashes.SHA256(), 'CV_HMAC_SHA256_N', 'cv_hmac_sha256')):
        out.write('#define %s 20\n' % n)
        for i in range(20):
            key = rb(RNG.randrange(0, 81))
            msg = rb(RNG.randrange(0, 129))
            hm = hmac.HMAC(key, h)
            hm.update(msg)
            mac = hm.finalize()
            out.write('static const struct cv_hash_vec %s_%d = {\n' % (tag, i))
            out.write('    {%s}, %d,\n    {%s}, %d,\n    {%s}, %d\n};\n\n' % (
                cinit(key), len(key), cinit(msg), len(msg), cinit(mac), len(mac)))
        out.write('static const struct cv_hash_vec *const %s[%s] = {\n' % (tag, n))
        out.write(',\n'.join('    &%s_%d' % (tag, i) for i in range(20)))
        out.write('\n};\n\n')

    # ---- arc4, first 16 keystream bytes (satoru) ----
    out.write('#define CV_ARC4_N 20\n')
    for i in range(20):
        key = rb(RNG.choice((5, 7, 8, 10, 16, 20, 24, 32)))
        enc = Cipher(algorithms.ARC4(key), mode=None).encryptor()
        outb = enc.update(b'\x00' * 16)
        out.write('static const struct cv_arc4_vec cv_arc4_%d = {\n' % i)
        out.write('    {%s}, %d, {%s}\n};\n\n' % (cinit(key), len(key), cinit(outb)))
    out.write('static const struct cv_arc4_vec *const cv_arc4[CV_ARC4_N] = {\n')
    out.write(',\n'.join('    &cv_arc4_%d' % i for i in range(20)))
    out.write('\n};\n\n')

    # ---- aes key wrap (RFC 3394), random keks (satoru) ----
    out.write('#define CV_UNWRAP_N 10\n')
    for i in range(10):
        kek = rb(16)
        pt = rb(RNG.choice((16, 24, 32)))
        wrapped = aes_key_wrap(kek, pt)
        out.write('static const struct cv_unwrap_vec cv_unwrap_%d = {\n' % i)
        out.write('    {%s},\n    {%s}, %d,\n    {%s}, %d\n};\n\n' % (
            cinit(kek), cinit(wrapped), len(wrapped), cinit(pt), len(pt)))
    out.write('static const struct cv_unwrap_vec *const cv_unwrap[CV_UNWRAP_N] = {\n')
    out.write(',\n'.join('    &cv_unwrap_%d' % i for i in range(10)))
    out.write('\n};\n\n')

    out.write('#endif\n')
    out.write('// end (satoru)\n')


if __name__ == '__main__':
    emit(sys.stdout)

# end (satoru)
