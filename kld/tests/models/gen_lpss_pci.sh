#!/bin/bash
# generate the LPSS I2C controller's config image from THIS laptop.
# read-only; the plain lspci works, sudo -n is only a fallback. (satoru)
set -eu
BDF=${BDF:-80:15.1}
OUT=${1:-$(dirname "$0")/lpss_i2c1_pci.h}
TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT
if ! lspci -s "$BDF" -nn -xxx > "$TMP" 2>/dev/null; then
    sudo -n lspci -s "$BDF" -nn -xxx > "$TMP"
fi
python3 - "$TMP" "$OUT" "$BDF" <<'PY'
import sys,re
txt=open(sys.argv[1]).read().splitlines()
out=open(sys.argv[2],'w')
bdf=sys.argv[3]
out.write('// generated by gen_lpss_pci.sh from lspci -s %s -nn -xxx\n' % bdf)
out.write('// source: this laptop, read-only.\n')
out.write('#ifndef KLD_LPSS_I2C1_PCI_H\n#define KLD_LPSS_I2C1_PCI_H\n\n')
vendor=device=subv=subd=None
for line in txt:
    m=re.search(r'\[([0-9a-f]{4}):([0-9a-f]{4})\]',line)
    if m and 'Serial bus' in line:
        vendor=int(m.group(1),16); device=int(m.group(2),16)
    m=re.search(r'Subsystem:\s*.*\[([0-9a-f]{4}):([0-9a-f]{4})\]',line)
    if m:
        subv=int(m.group(1),16); subd=int(m.group(2),16)
bytes_={}
for line in txt:
    m=re.match(r'^([0-9a-f]{2}):((?:\s+[0-9a-f]{2})+)',line)
    if m:
        off=int(m.group(1),16)
        for i,b in enumerate(m.group(2).split()):
            bytes_[off+i]=int(b,16)
out.write('#define LPSS_PCI_VENDOR 0x%04x\n' % (vendor or 0x8086))
out.write('#define LPSS_PCI_DEVICE 0x%04x\n' % (device or 0x7f4d))
out.write('#define LPSS_PCI_SUBVENDOR 0x%04x\n' % (subv or 0x17aa))
out.write('#define LPSS_PCI_SUBDEVICE 0x%04x\n' % (subd or 0x3d6c))
out.write('#define LPSS_PCI_CLASS 0x0c8000\n')
out.write('#define LPSS_PCI_REVISION 0x10\n\n')
out.write('static const unsigned char lpss_pci_config[256] = {\n')
for off in range(0,256,16):
    vals=', '.join('0x%02x' % bytes_.get(off+i,0) for i in range(16))
    out.write('    %s,%s\n' % (vals, '  // 0x%02x' % off))
out.write('};\n\n#endif\n// end (satoru)\n')
PY
