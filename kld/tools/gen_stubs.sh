#!/bin/bash
# gen_stubs - emit an aborting stub for every driver symbol nothing provides.
#
# This is what makes the doc's "every referenced symbol exists, all panic with
# LX_UNIMPL" automatic instead of a manual transcription exercise. Run after
# compiling the driver objects and before linking the container.
#
# Usage: gen_stubs.sh <builddir> <out.c>
#
# Three exclusions, each of which caused a real failure when it was missing:
#  1. The driver's OWN definitions. A reference from phy.o resolved by ich8lan.o
#     is intra-driver; stubbing it gives "multiple definition" at link.
#  2. The PREVIOUS build's lx_stubs_gen.o. It defines all 185 stubs, so counting
#     it as "provided" makes the generator emit an empty file and the link fails
#     with the very symbols it was supposed to cover.
#  3. libc + compiler builtins. Stubbing memcpy would shadow the real one.
#
# LIMITATION, stated because it will bite: a stub is emitted as a zero-arg
# function. That satisfies the LINKER for both function and data references (C
# has no mangling), and calling one aborts loudly as intended. But a reference
# READ AS DATA (an exported variable, a struct, a static_key) will read the
# stub's code bytes as a value instead of aborting. The census already shows
# several of these for e1000e - phys_base, vmemmap_base, __this_module,
# param_ops_int, system_wq - and they must become real data in lx_emul. A
# nm-type-aware pass cannot fix this from the driver side alone, because an
# undefined symbol carries no type; it needs the type from the DEFINING kernel
# build (readelf on the real vmlinux/module).
# end (satoru)
set -u
BUILD="${1:-build}"
OUT="${2:-$BUILD/lx_stubs_gen.c}"

DRV_OBJS=$(find "$BUILD/driver" -name '*.o' 2>/dev/null)
# imported upstream cores: their undefined symbols need providers too, and
# their definitions provide for the driver. (satoru)
CORE_OBJS=$(find "$BUILD/core" -name '*.o' 2>/dev/null || true)
# (2) hand-written emul only - never the generated stub object
EMUL_HAND=$(find "$BUILD/emul" -name '*.o' 2>/dev/null | grep -v 'lx_stubs_gen' || true)

if [ -z "$DRV_OBJS" ]; then
  echo "gen_stubs: no driver objects in $BUILD/driver" >&2
  exit 1
fi

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

nm --undefined-only $DRV_OBJS $CORE_OBJS 2>/dev/null \
  | awk '$1=="U"{print $2}' | sort -u > "$TMP/needed"

{
  [ -n "$EMUL_HAND" ] && nm --defined-only $EMUL_HAND 2>/dev/null | awk '{print $3}'
  # (1) intra-driver definitions
  nm --defined-only $DRV_OBJS $CORE_OBJS 2>/dev/null | awk '{print $3}'
  # (3) libc + compiler builtins
  printf '%s\n' memcpy memset memmove memcmp strlen strcmp strncmp strcpy strncpy \
                strchr strrchr strstr strnlen snprintf vsnprintf sprintf printf \
                puts malloc free calloc realloc abort exit _exit write read \
                __stack_chk_fail __stack_chk_guard __memcpy_chk __memset_chk \
                __udivdi3 __umoddi3 __divdi3 __moddi3
  # linker-synthesised: cannot be stubbed, the linker provides it
  printf '%s\n' _GLOBAL_OFFSET_TABLE_
} 2>/dev/null | sort -u > "$TMP/provided"

comm -23 "$TMP/needed" "$TMP/provided" > "$TMP/tostub"
N=$(wc -l < "$TMP/tostub")

mkdir -p "$(dirname "$OUT")"
{
  echo "// AUTO-GENERATED by kld/tools/gen_stubs.sh - do not edit."
  echo "// One aborting stub per driver symbol lx_emul does not yet provide."
  echo "// Implementing one means moving it into lx_emul; this file then shrinks"
  echo "// on the next build. The count here IS the phase-2 backlog. (satoru)"
  echo "//"
  echo "// stub count: $N"
  echo
  echo '#include "lx_emul.h"'
  echo
  while read -r s; do
    [ -z "$s" ] && continue
    echo "LX_STUB($s)"
  done < "$TMP/tostub"
  echo
  echo "// end (satoru)"
} > "$OUT"

echo "gen_stubs: emitted $N stubs -> $OUT"
