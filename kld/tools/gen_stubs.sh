#!/bin/bash
# gen_stubs - emit an aborting stub for every driver symbol nothing provides.
#
# This is what makes the doc's "every referenced symbol exists, all panic with
# LX_UNIMPL" automatic instead of a manual transcription exercise. Run after
# compiling the driver objects and before linking the container.
#
# Usage: gen_stubs.sh <builddir> <out.c>
#
# Three exclusions, each of which caused a real failure when it was missing:
#  1. The driver's OWN definitions. A reference from phy.o resolved by ich8lan.o
#     is intra-driver; stubbing it gives "multiple definition" at link.
#  2. The PREVIOUS build's lx_stubs_gen.o. It defines all 185 stubs, so counting
#     it as "provided" makes the generator emit an empty file and the link fails
#     with the very symbols it was supposed to cover.
#  3. libc + compiler builtins. Stubbing memcpy would shadow the real one.
#
# DATA CLASSIFICATION: an undefined symbol carries no type, but the relocation
# does. A call is R_X86_64_PLT32; a data reference is PC32/32/32S/64/GOTPCREL
# (and its REX/GOTPCRELX variants). A symbol referenced ONLY through data
# relocations is DATA: emitting a function stub for it would make the driver
# read the stub's code bytes as a value (this is how _ctype silently corrupted
# acpica's namespace lookups). Those symbols are MISSING and FAIL the link with
# their name and a referencing object; only functions get a stub. (satoru)
# end (satoru)
set -u
BUILD="${1:-build}"
OUT="${2:-$BUILD/lx_stubs_gen.c}"

DRV_OBJS=$(find "$BUILD/driver" -name '*.o' 2>/dev/null)
# imported upstream cores: their undefined symbols need providers too, and
# their definitions provide for the driver. (satoru)
CORE_OBJS=$(find "$BUILD/core" -name '*.o' 2>/dev/null || true)
# (2) hand-written emul only - never the generated stub object
EMUL_HAND=$(find "$BUILD/emul" -name '*.o' 2>/dev/null | grep -v 'lx_stubs_gen' || true)

if [ -z "$DRV_OBJS" ] && [ -z "$CORE_OBJS" ]; then
  # a pure test family has no upstream driver/core objects; there is nothing
  # to stub on top of the shim. (satoru)
  mkdir -p "$(dirname "$OUT")"
  { echo "// AUTO-GENERATED by kld/tools/gen_stubs.sh - do not edit."; echo "// no driver/core objects: empty stub set (test-only family)."; echo "// end (satoru)"; } > "$OUT"
  echo "gen_stubs: no driver/core objects, empty stub set -> $OUT"
  exit 0
fi

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

nm --undefined-only $DRV_OBJS $CORE_OBJS 2>/dev/null \
  | awk '$1=="U"{print $2}' | sort -u > "$TMP/needed"

{
  [ -n "$EMUL_HAND" ] && nm --defined-only $EMUL_HAND 2>/dev/null | awk '{print $3}'
  # (1) intra-driver definitions
  nm --defined-only $DRV_OBJS $CORE_OBJS 2>/dev/null | awk '{print $3}'
  # (3) libc + compiler builtins
  printf '%s\n' memcpy memset memmove memcmp memchr strlen strcmp strncmp strcpy strncpy \
                strcat strchr strrchr strstr strnlen snprintf vsnprintf sprintf printf \
                puts malloc free calloc realloc abort exit _exit write read \
                __stack_chk_fail __stack_chk_guard __memcpy_chk __memset_chk \
                __udivdi3 __umoddi3 __divdi3 __moddi3
  # linker-synthesised: cannot be stubbed, the linker provides it
  printf '%s\n' _GLOBAL_OFFSET_TABLE_
} 2>/dev/null | sort -u > "$TMP/provided"

comm -23 "$TMP/needed" "$TMP/provided" > "$TMP/tostub"

# how each unresolved symbol is referenced: PLT32 = call, the rest = data.
objdump -r $DRV_OBJS $CORE_OBJS 2>/dev/null | awk '
  /^[^ \t].*\.o:/ { f = $1; sub(/:$/, "", f); next }
  NF >= 3 && $2 ~ /^R_X86_64_/ {
    s = $3; sub(/[-+]0x[0-9a-f]+$/, "", s)
    print s, $2, f
  }
' > "$TMP/relmap"

: > "$TMP/func"
: > "$TMP/data"
while read -r s; do
  [ -z "$s" ] && continue
  types=$(awk -v s="$s" '$1 == s { print $2 }' "$TMP/relmap")
  if echo "$types" | grep -q 'R_X86_64_PLT32'; then
    echo "$s" >> "$TMP/func"
  elif echo "$types" | grep -qE 'R_X86_64_(REX_GOTPCRELX|GOTPCRELX|GOTPCREL|PC32|32S|32|64)'; then
    obj=$(awk -v s="$s" '$1 == s && $2 !~ /PLT32/ { print $3; exit }' "$TMP/relmap")
    echo "gen_stubs: MISSING DATA symbol '$s' (referenced as data by ${obj:-unknown})" >&2
    echo "$s" >> "$TMP/data"
  else
    # no relocation record (e.g. a linker-script symbol): keep the old
    # behaviour, a call is the common case. (satoru)
    echo "$s" >> "$TMP/func"
  fi
done < "$TMP/tostub"

ND=$(wc -l < "$TMP/data")
if [ "$ND" -gt 0 ]; then
  if [ "${KLD_DATA_LENIENT:-}" = 1 ]; then
    # the drm and mt76 families predate the data check and take function
    # addresses in initializers (kill_anon_super, debugfs_attr_read), which
    # look like data to a relocation scan. they keep the old behaviour, with
    # the count reported, until their providers are audited. (satoru)
    echo "gen_stubs: WARNING $ND symbol(s) referenced as data are stubbed as functions (lenient family)" >&2
    cat "$TMP/data" >> "$TMP/func"
    sort -u "$TMP/func" -o "$TMP/func"
  else
    echo "gen_stubs: refusing $ND function stub(s) for DATA symbols; add real providers" >&2
    exit 1
  fi
fi

N=$(wc -l < "$TMP/func")

mkdir -p "$(dirname "$OUT")"
{
  echo "// AUTO-GENERATED by kld/tools/gen_stubs.sh - do not edit."
  echo "// One aborting stub per driver FUNCTION lx_emul does not yet provide."
  echo "// Data symbols are never stubbed: they fail the build instead. (satoru)"
  echo "//"
  echo "// stub count: $N"
  echo
  echo '#include "lx_emul.h"'
  echo
  while read -r s; do
    [ -z "$s" ] && continue
    echo "LX_STUB($s)"
  done < "$TMP/func"
  echo
  echo "// end (satoru)"
} > "$OUT"

echo "gen_stubs: emitted $N function stubs -> $OUT"
