#!/usr/bin/env python3
# gen_acpi_blob - turn an acpidump/acpixtract capture directory into a C array
# the KLD container links. the tables are the laptop's firmware and are NEVER
# tracked by git: the output lives under kld/build, which is ignored.
#
#   gen_acpi_blob.py --tables DIR --out FILE
#
# MSDM (Windows product key) and SLIC are dropped on purpose; neither is used
# by any driver on the touchpad path and neither belongs in a test image.
#
# the runtime provider (lx_acpi_tables.c) copies these bytes into its arena,
# repoints the FADT at the arena's DSDT/FACS and synthesizes RSDP/XSDT. (satoru)
#
# end (satoru)
import argparse
import os
import struct
import sys

EXCLUDE = {b"MSDM", b"SLIC"}


def read_tables(directory):
    if not os.path.isdir(directory):
        sys.stderr.write(
            "gen_acpi_blob: no ACPI table directory at %s\n"
            "  run: sudo -n acpidump -o /tmp/acpi.dump && acpixtract ...\n"
            "  or set ACPI_TABLES=<dir of one raw *.dat per table>\n" % directory)
        return None
    tables = []
    for name in sorted(os.listdir(directory)):
        if not name.lower().endswith(".dat"):
            continue
        path = os.path.join(directory, name)
        with open(path, "rb") as f:
            data = f.read()
        if len(data) < 36:
            sys.stderr.write("gen_acpi_blob: %s shorter than an ACPI header\n" % path)
            return None
        sig = data[0:4]
        length = struct.unpack_from("<I", data, 4)[0]
        if length < 36 or length > len(data):
            sys.stderr.write("gen_acpi_blob: %s has length %u, file %u\n" %
                             (path, length, len(data)))
            return None
        if sig in EXCLUDE:
            continue
        tables.append((sig, data[:length]))
    if not tables:
        sys.stderr.write("gen_acpi_blob: no usable tables in %s\n" % directory)
        return None
    return tables


def emit(out, tables):
    blob = bytearray()
    index = []
    for sig, data in tables:
        index.append((sig.decode("ascii", "replace"), len(data), len(blob)))
        blob += data
    with open(out, "w") as f:
        f.write("// AUTO-GENERATED by kld/tools/gen_acpi_blob.py from the capture\n")
        f.write("// directory; the firmware tables are not tracked by git. do not edit.\n")
        f.write("// end (satoru)\n\n")
        f.write('#include "kimpl/lx_acpi.h"\n\n')
        f.write("const unsigned int lx_acpi_blob_ntables = %u;\n\n" % len(index))
        f.write("const unsigned char lx_acpi_blob_data[] = {\n")
        for i in range(0, len(blob), 16):
            f.write("    " + ",".join("0x%02x" % b for b in blob[i:i + 16]) + ",\n")
        f.write("};\n\n")
        f.write("const struct lx_acpi_blob_table lx_acpi_blob_tables[] = {\n")
        for sig, length, offset in index:
            f.write("    { %u, %u }, /* %s */\n" % (length, offset, sig))
        f.write("};\n\n")
        f.write("// end (satoru)\n")
    sys.stderr.write("gen_acpi_blob: %u tables, %u bytes -> %s\n" %
                     (len(index), len(blob), out))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tables", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    tables = read_tables(args.tables)
    if tables is None:
        return 2
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    emit(args.out, tables)
    return 0


if __name__ == "__main__":
    sys.exit(main())

