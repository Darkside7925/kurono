#!/bin/bash
# gen_headers - reproduce the generated headers a real kernel build creates.
#
# Out-of-tree module builds normally run against a CONFIGURED kernel tree, which
# has already produced:
#   * include/generated/autoconf.h         (from .config)
#   * include/generated/uapi/linux/version.h
#   * asm/ wrappers for every asm-generic header the arch does not override
#     (the mandatory-y / generic-y mechanism in scripts/Makefile.asm-headers)
#
# We vendor headers only, so we synthesize the same thing. This is faithful
# reproduction of the upstream mechanism, not a hack: the wrapper contents are
# byte-identical to what Kbuild emits.
#
# Usage: gen_headers.sh   (run from kld/)
# end (satoru)
set -u
KVER=$(cat KLD_KERNEL_VERSION)
L=../third_party/linux-$KVER
OUT=lx_emul/shim-include

if [ ! -d "$L/include/linux" ]; then
  echo "gen_headers: vendored tree missing: $L" >&2
  exit 1
fi

mkdir -p "$OUT/asm" "$OUT/generated/uapi/linux" "$OUT/generated"

# ── 1) asm/ wrappers ────────────────────────────────────────────────────────
# for each mandatory-y / generic-y header, if the arch does not provide its own
# asm/<h>, emit the same one-line wrapper Kbuild would. (satoru)
emit_wrappers() {
  local kbuild="$1" gendir="$2"
  [ -f "$kbuild" ] || return 0
  grep -hoE '^(mandatory-y|generic-y)[[:space:]]*\+=[[:space:]]*[A-Za-z0-9_./-]+\.h' "$kbuild" \
    | awk '{print $NF}' | sort -u | while read -r h; do
      # arch override wins - never shadow a real x86 header
      if [ -f "$L/arch/x86/include/asm/$h" ] || [ -f "$L/arch/x86/include/uapi/asm/$h" ]; then
        continue
      fi
      if [ -f "$L/$gendir/$h" ]; then
        printf '#include <%s>\n' "$(basename "$gendir")/$h" > "$OUT/asm/$h"
      fi
    done
}
emit_wrappers "$L/include/uapi/asm-generic/Kbuild" "include/uapi/asm-generic"
emit_wrappers "$L/include/asm-generic/Kbuild"      "include/asm-generic"
emit_wrappers "$L/arch/x86/include/asm/Kbuild"     "include/asm-generic"

NW=$(ls "$OUT/asm" 2>/dev/null | wc -l)

# ── 2) version.h ────────────────────────────────────────────────────────────
V=${KVER%%.*}; R=${KVER#*.}; P=${R#*.}; R=${R%%.*}
CODE=$(( (V << 16) + (R << 8) + (P > 255 ? 255 : P) ))
cat > "$OUT/generated/uapi/linux/version.h" <<EOF
/* AUTO-GENERATED by kld/tools/gen_headers.sh - mirrors Kbuild output. */
#define LINUX_VERSION_CODE $CODE
#define KERNEL_VERSION(a,b,c) (((a) << 16) + ((b) << 8) + ((c) > 255 ? 255 : (c)))
#define LINUX_VERSION_MAJOR $V
#define LINUX_VERSION_PATCHLEVEL $R
#define LINUX_VERSION_SUBLEVEL $P
EOF

# ── 3) autoconf.h ───────────────────────────────────────────────────────────
# The CONFIG_* set the container is built against. This is a real configuration
# decision, not boilerplate: it decides which code paths inside the driver are
# even compiled. Kept deliberately MINIMAL - a 64-bit PCI x86 build with the
# optional kernel features a userspace container cannot honour switched OFF.
# Every addition here should be justified, because each one enables driver code
# that lx_emul must then support. (satoru)
cat > "$OUT/generated/autoconf.h" <<'EOF'
/* AUTO-GENERATED by kld/tools/gen_headers.sh - the KLD container's kconfig. */
#ifndef KLD_AUTOCONF_H
#define KLD_AUTOCONF_H

/* architecture */
#define CONFIG_X86              1
#define CONFIG_X86_64           1
#define CONFIG_64BIT            1
#define CONFIG_PHYS_ADDR_T_64BIT 1
#define CONFIG_ARCH_DMA_ADDR_T_64BIT 1
#define CONFIG_PAGE_SHIFT       12
#define CONFIG_NR_CPUS          8
#define CONFIG_HZ               1000
#define CONFIG_BASE_SMALL       0

/* buses / core subsystems the driver needs */
#define CONFIG_PCI              1
#define CONFIG_PCI_MSI          1
#define CONFIG_NET              1
#define CONFIG_ETHERNET         1
#define CONFIG_INET             1

/* deliberately OFF: each of these would pull in machinery a userspace
 * container cannot provide, and leaving them off shrinks the shim surface.
 * Turning any of them on is a phase-2 decision with a cost. (satoru)
 *   CONFIG_SMP          - driver per-cpu paths
 *   CONFIG_PREEMPT*     - preempt counting
 *   CONFIG_LOCKDEP      - lock validator
 *   CONFIG_TRACEPOINTS  - ftrace hooks
 *   CONFIG_PM / PM_SLEEP- suspend/resume callbacks
 *   CONFIG_XPS / RPS    - multiqueue steering
 *   CONFIG_PTP_1588_CLOCK - e1000e timestamping
 */

#endif /* KLD_AUTOCONF_H */
EOF

# ── 4) timeconst.h ──────────────────────────────────────────────────────────
# include/linux/jiffies.h needs the HZ-derived conversion constants that Kbuild
# produces by running kernel/time/timeconst.bc through bc. These are numeric
# constants where a hand-typed guess would be silently wrong, so generate them
# from the upstream script if we can, and refuse to fabricate them if we cannot.
# (satoru)
TC="$OUT/generated/timeconst.h"
if [ ! -f "$TC" ]; then
  BC_SRC=""
  for c in "$L/kernel/time/timeconst.bc" "/var/tmp/linux-$KVER/kernel/time/timeconst.bc"; do
    [ -f "$c" ] && BC_SRC="$c" && break
  done
  if [ -n "$BC_SRC" ] && command -v bc >/dev/null 2>&1; then
    HZ=$(grep -oE '^#define CONFIG_HZ[[:space:]]+[0-9]+' "$OUT/generated/autoconf.h" | awk '{print $NF}')
    HZ=${HZ:-1000}
    echo "$HZ" | bc -q "$BC_SRC" > "$TC"
    echo "gen_headers: timeconst.h generated for HZ=$HZ via $BC_SRC"
  else
    echo "gen_headers: WARNING cannot generate timeconst.h" >&2
    echo "gen_headers:   need kernel/time/timeconst.bc + bc(1)." >&2
    echo "gen_headers:   NOT fabricating HZ constants - jiffies.h will fail to" >&2
    echo "gen_headers:   compile, which is the honest outcome. Extract the .bc:" >&2
    echo "gen_headers:   tar -xf linux-$KVER.tar.xz linux-$KVER/kernel/time/timeconst.bc" >&2
  fi
fi

echo "gen_headers: $NW asm/ wrappers, version.h (code $CODE), autoconf.h"
